#!/usr/bin/env python3
"""
Helper script to set up Google API credentials for the Tag Extractor API.
This script helps you configure your .env.local file with Google credentials.
"""

import os
import json
import sys
from pathlib import Path

def setup_credentials():
    """Interactive setup for Google API credentials"""
    
    print("=" * 60)
    print("Google Slides API Credentials Setup")
    print("=" * 60)
    print()
    
    # Check if .env.local exists
    env_file = Path(".env.local")
    env_exists = env_file.exists()
    
    if env_exists:
        print(f"Found existing .env.local file")
        response = input("Do you want to update it? (y/n): ").strip().lower()
        if response != 'y':
            print("Setup cancelled.")
            return
    else:
        print("Creating new .env.local file...")
    
    # Get OpenAI API key
    print("\n1. OpenAI API Key")
    if env_exists:
        print("   (Press Enter to keep existing value)")
    openai_key = input("   Enter your OpenAI API key: ").strip()
    
    # Get Google credentials method
    print("\n2. Google API Credentials")
    print("   Choose setup method:")
    print("   [1] Use service account JSON file path (Recommended)")
    print("   [2] Use service account JSON content as string")
    print("   [3] Skip (configure manually later)")
    
    method = input("   Enter choice (1/2/3): ").strip()
    
    google_creds = None
    google_key = None
    
    if method == "1":
        print("\n   Using file path method")
        file_path = input("   Enter full path to your service account JSON file: ").strip()
        
        # Remove quotes if user added them
        file_path = file_path.strip('"').strip("'")
        
        # Convert to absolute path
        if not os.path.isabs(file_path):
            file_path = os.path.abspath(file_path)
        
        # Verify file exists
        if not os.path.exists(file_path):
            print(f"   ERROR: File not found at {file_path}")
            print("   Please check the path and try again.")
            return
        
        # Verify it's a valid JSON file
        try:
            with open(file_path, 'r') as f:
                json.load(f)
            google_creds = file_path
            google_key = "GOOGLE_APPLICATION_CREDENTIALS"
            print(f"   ✓ Valid JSON file found")
        except json.JSONDecodeError:
            print("   ERROR: File is not a valid JSON file")
            return
        except Exception as e:
            print(f"   ERROR: {str(e)}")
            return
            
    elif method == "2":
        print("\n   Using JSON content method")
        print("   Paste your service account JSON content (press Enter, then Ctrl+D on Mac/Linux or Ctrl+Z on Windows to finish):")
        json_lines = []
        try:
            while True:
                line = input()
                json_lines.append(line)
        except EOFError:
            pass
        
        json_content = '\n'.join(json_lines).strip()
        
        # Verify it's valid JSON
        try:
            json.loads(json_content)
            google_creds = json_content
            google_key = "GOOGLE_SERVICE_ACCOUNT_JSON"
            print("   ✓ Valid JSON content")
        except json.JSONDecodeError:
            print("   ERROR: Invalid JSON content")
            return
    
    # Read existing .env.local if it exists
    env_vars = {}
    if env_exists:
        with open(env_file, 'r') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    key, value = line.split('=', 1)
                    env_vars[key.strip()] = value.strip()
    
    # Update environment variables
    if openai_key:
        env_vars['OPENAI_API_KEY'] = openai_key
    elif 'OPENAI_API_KEY' not in env_vars:
        print("\n   WARNING: No OpenAI API key provided. You'll need to add it manually.")
    
    if google_creds and google_key:
        env_vars[google_key] = google_creds
        print(f"\n   ✓ Google credentials configured using {google_key}")
    
    # Write .env.local file
    try:
        with open(env_file, 'w') as f:
            f.write("# Environment variables for Tag Extractor API\n")
            f.write("# This file is automatically generated. Do not commit to git.\n\n")
            
            if 'OPENAI_API_KEY' in env_vars:
                f.write(f"OPENAI_API_KEY={env_vars['OPENAI_API_KEY']}\n")
            
            if google_key and google_key in env_vars:
                if google_key == "GOOGLE_APPLICATION_CREDENTIALS":
                    f.write(f"GOOGLE_APPLICATION_CREDENTIALS={env_vars[google_key]}\n")
                else:
                    # For JSON content, we need to handle it carefully
                    f.write(f"{google_key}='{env_vars[google_key]}'\n")
            
            # Write any other existing variables
            for key, value in env_vars.items():
                if key not in ['OPENAI_API_KEY', 'GOOGLE_APPLICATION_CREDENTIALS', 'GOOGLE_SERVICE_ACCOUNT_JSON']:
                    f.write(f"{key}={value}\n")
        
        print(f"\n✓ Successfully created/updated .env.local file")
        print(f"\nNext steps:")
        print(f"1. Make sure you've shared your Google Slides presentation with the service account email")
        print(f"2. Restart your FastAPI server")
        print(f"3. Test the API endpoint")
        
    except Exception as e:
        print(f"\nERROR: Failed to write .env.local file: {str(e)}")
        return

if __name__ == "__main__":
    try:
        setup_credentials()
    except KeyboardInterrupt:
        print("\n\nSetup cancelled by user.")
        sys.exit(0)

